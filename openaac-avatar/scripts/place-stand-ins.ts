/**
 * Places the stand-in hands (art/stand-ins/*.svg) on the figure at each wrist,
 * for both body extremes, and writes them as add-on art files the compiler merges.
 *
 *   pnpm art:stand-ins
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseInkscapeSvg } from '@openaac-avatar/artkit';

const root = resolve(import.meta.dirname, '..');

/** Stand-in → variant name, per view. `name` maps a stand-in piece to the part name it becomes. */
const VIEWS: { view: string; hands: { file: string; variant: string; name?: (piece: string) => string }[] }[] = [
  {
    view: 'front',
    hands: [
      { file: 'hand-relaxed.svg', variant: 'relaxed' },
      { file: 'hand-rest.svg', variant: 'rest' },
      { file: 'hand-point.svg', variant: 'point' },
    ],
  },
  {
    // The ¾ art's hand is one piece (`arm_X_hand`): the gripping palm replaces it as `arm_X_hand@grip`.
    view: 'three-quarter',
    hands: [{ file: 'hand-grip.svg', variant: 'grip', name: (piece) => (piece === 'palm' ? 'hand' : piece) }],
  },
  {
    // The side art's hand is one piece (`arm_L_hand`), so the waving hand replaces it as `arm_L_hand@wave`.
    view: 'side',
    hands: [
      { file: 'hand-wave.svg', variant: 'wave', name: (piece) => (piece === 'palm' ? 'hand' : `hand_${piece}`) },
      // Holding a utensil: the front art's gripping hand, as in the ¾ view.
      { file: 'hand-grip.svg', variant: 'grip', name: (piece) => (piece === 'palm' ? 'hand' : piece) },
    ],
  },
];

/** Hand size relative to the stand-in drawing, per body extreme (matches the designer's open hand). */
const SCALE = { low: 1.0, high: 1.12 } as const;

function pathsOf(svg: string): { id: string; d: string; attrs: string }[] {
  const out: { id: string; d: string; attrs: string }[] = [];
  for (const m of svg.matchAll(/<path\s+([^>]*?)\/>/g)) {
    const a = m[1]!;
    const id = /id="([^"]+)"/.exec(a)?.[1];
    const d = /\sd="([^"]+)"/.exec(' ' + a)?.[1]?.replace(/\s+/g, ' ');
    if (!id || !d || id === 'lines') continue;
    out.push({ id, d, attrs: a.replace(/\s*id="[^"]*"/, '').replace(/\s*d="[^"]*"/, '') });
  }
  return out;
}

for (const { view, hands } of VIEWS) {
  const src = join(root, 'art/source', view);
  const outDir = join(src, 'addons');
  mkdirSync(outDir, { recursive: true });
  for (const extreme of ['low', 'high'] as const) {
    const art = parseInkscapeSvg(readFileSync(join(src, `bm_${extreme}.svg`), 'utf8'), `bm_${extreme}.svg`);
    const groups: string[] = [];
    for (const side of ['R', 'L'] as const) {
      const wrist = art.pivots.get(`wrist_${side}`);
      const elbow = art.pivots.get(`elbow_${side}`);
      if (!wrist || !elbow) continue; // e.g. the side view has only the near (left) arm
      const angle = (Math.atan2(wrist[1] - elbow[1], wrist[0] - elbow[0]) * 180) / Math.PI;
      const s = SCALE[extreme];
      // The stand-in is a right hand; the left hand is its mirror image (thumb on the other side of the forearm).
      const flip = side === 'L' ? -s : s;
      for (const hand of hands) {
        const paths = pathsOf(readFileSync(join(root, 'art/stand-ins', hand.file), 'utf8'))
          .map((p) => {
            // Keep the outline at the style-guide weight after scaling.
            const attrs = p.attrs.trim().replace(/stroke-width="([\d.]+)"/, (_m: string, w: string) => `stroke-width="${(Number(w) / s).toFixed(4)}"`);
            const name = hand.name ? hand.name(p.id) : p.id;
            return `    <path inkscape:label="arm_${side}_${name}@${hand.variant}" d="${p.d}" ${attrs}/>`;
          })
          .join('\n');
        groups.push(
          `  <g inkscape:label="arm_${side}_hand@${hand.variant}" transform="translate(${wrist[0].toFixed(3)} ${wrist[1].toFixed(3)}) rotate(${angle.toFixed(3)}) scale(${s} ${flip})">\n${paths}\n  </g>`,
        );
      }
    }
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/place-stand-ins.ts from art/stand-ins/. Do not edit; delete when the designer's versions exist. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="1000" height="1000" viewBox="0 0 1000 1000">
${groups.join('\n')}
</svg>
`;
    writeFileSync(join(outDir, `stand-in-hands.${extreme}.svg`), svg);
    console.log(`wrote art/source/${view}/addons/stand-in-hands.${extreme}.svg`);
  }
}
