/**
 * Makes art/stand-ins/hand-wave.svg from the designer's open right hand in the
 * front art (arm_R_palm@open, arm_R_thumb@open, slim extreme), moved into the
 * stand-in frame: wrist at 0,0, fingers along +x. Used as the waving hand in
 * views that only have a hanging hand (side view).
 *
 *   tsx --conditions=source scripts/make-wave-hand.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseInkscapeSvg } from '@openaac-avatar/artkit';
import { applyToSubpath, multiply, rotate, toPathData, translate } from '@openaac-avatar/core';

const root = resolve(import.meta.dirname, '..');
const art = parseInkscapeSvg(readFileSync(join(root, 'art/source/front/bm_low.svg'), 'utf8'), 'bm_low.svg');
const wrist = art.pivots.get('wrist_R')!;
const elbow = art.pivots.get('elbow_R')!;
const angle = (Math.atan2(wrist[1] - elbow[1], wrist[0] - elbow[0]) * 180) / Math.PI;
// Into the local frame: wrist to the origin, forearm direction to +x.
const m = multiply(rotate(-angle), translate(-wrist[0], -wrist[1]));
const pieces = [
  ['palm', 'arm_R_palm@open'],
  ['thumb', 'arm_R_thumb@open'],
] as const;
const paths = pieces.map(([id, part]) => {
  const p = art.parts.find((q) => q.id === part);
  if (!p) throw new Error(`front art has no ${part}`);
  const d = toPathData(p.subpaths.map((sp) => applyToSubpath(m, sp)));
  return `  <path id="${id}" d="${d}" fill="#d59965" stroke="#000000" stroke-width="10" stroke-linecap="round" stroke-linejoin="round"/>`;
});
writeFileSync(
  join(root, 'art/stand-ins/hand-wave.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="-40 -100 200 200">
  <!-- Right hand, open, palm towards the viewer: the designer's front-view open hand (front art, slim), generated by scripts/make-wave-hand.ts. Wrist at 0,0; fingers along +x. -->
${paths.join('\n')}
</svg>
`,
);
console.log(`wrote art/stand-ins/hand-wave.svg (forearm angle ${angle.toFixed(1)}°)`);
